//! Thai text in exported and printed PDFs.
//!
//! The 14 standard PDF fonts cover WinAnsiEncoding only, and the predefined non-embedded
//! `STSong-Light` Adobe-GB1 CID font has no Thai glyphs. When the optional craft-fonts build input
//! supplies an OFL Thai face (see `build.rs`), Thai characters are set in a Type0 / Identity-H
//! font backed by a TrueType `/FontFile2`:
//!
//! - CID `n` is Unicode `U+0E00 + n - 1`, so a content stream writes two-byte CIDs.
//! - A `/CIDToGIDMap` stream maps each CID to the face's glyph id (read from its `cmap`).
//! - A `/ToUnicode` CMap maps each CID back to Unicode, so text extraction and search work.
//! - `/W` carries the face's advance widths, and [`char_width`] uses the same numbers so the
//!   layout that measures a cell draws it at that width.
//!
//! Without the build input [`available`] is false and [`crate::Page::text`] keeps the old CID
//! fallback: an ordinary build emits byte-identical PDFs. The face is never committed to this
//! repository; `docs/thai-printing.md` documents the craft-fonts row upstream adds.

use std::fmt::Write as _;
use std::sync::OnceLock;

use crate::embed;

/// Generated by `build.rs`: `Some(include_bytes!(...))` with `CRAFT_FONTS_DIR`, `None` otherwise.
mod generated {
    include!(concat!(env!("OUT_DIR"), "/thai_font.rs"));
}

const FIRST: u32 = 0x0E00;
const LAST: u32 = 0x0E7F;
/// CIDs 1..=128 cover the Thai block; CID 0 stays `.notdef`.
pub const CID_COUNT: usize = (LAST - FIRST + 1) as usize + 1;

/// Whether this build embedded a Thai face. Public through [`crate::thai_font_available`].
pub fn available() -> bool {
    generated::THAI_FONT_BYTES.is_some()
}

/// The embedded face's bytes, for the PDF `/FontFile2` stream.
pub fn font_bytes() -> Option<&'static [u8]> {
    generated::THAI_FONT_BYTES
}

/// The PDF `/BaseFont` name, derived from the manifest's family and style.
pub fn base_name() -> &'static str {
    generated::THAI_FONT_PS_NAME
}

/// True for a character in the Thai Unicode block (consonants, vowels, tone marks, digits, ฿).
pub fn is_thai(c: char) -> bool {
    (FIRST..=LAST).contains(&(c as u32))
}

/// The two-byte Identity-H CID for a Thai character.
pub fn cid(c: char) -> Option<u16> {
    let u = c as u32;
    (FIRST..=LAST).contains(&u).then(|| (u - FIRST + 1) as u16)
}

/// The Unicode character a CID stands for.
fn character(id: u16) -> Option<char> {
    char::from_u32(FIRST + u32::from(id) - 1)
}

struct Parsed {
    /// Glyph id per CID, CID 0 first.
    gids: Vec<u16>,
    /// Advance width in 1/1000 em per CID, CID 0 first.
    widths: Vec<u16>,
    /// `/FontDescriptor` entries measured from the face.
    descriptor: String,
}

fn parse() -> Option<Parsed> {
    let face = embed::Face::parse(font_bytes()?)?;
    let mut gids = Vec::with_capacity(CID_COUNT);
    let mut widths = Vec::with_capacity(CID_COUNT);
    gids.push(0);
    widths.push(0);
    for id in 1..CID_COUNT {
        let code = FIRST + (id as u32 - 1);
        let gid = face.glyph_id(code);
        gids.push(gid);
        widths.push(face.width(gid));
    }
    Some(Parsed { gids, widths, descriptor: face.descriptor_entries() })
}

/// Only reachable in a build without the face, where no Thai run is ever set in this font.
fn fallback() -> Parsed {
    Parsed {
        gids: vec![0; CID_COUNT],
        widths: vec![500; CID_COUNT],
        descriptor: String::from("/FontBBox [-200 -300 1100 1000] /ItalicAngle 0 /Ascent 1000 /Descent -300 /CapHeight 700 /StemV 80"),
    }
}

static PARSED: OnceLock<Parsed> = OnceLock::new();
fn parsed() -> &'static Parsed {
    PARSED.get_or_init(|| parse().unwrap_or_else(fallback))
}

/// The advance width of a Thai character in 1/1000 em, for [`crate::Font::char_width`].
pub fn char_width(c: char) -> u16 {
    let Some(id) = cid(c) else { return 0 };
    parsed().widths.get(usize::from(id)).copied().unwrap_or(0)
}

/// The `/CIDToGIDMap` stream: two-byte big-endian glyph ids indexed by CID.
pub fn cid_to_gid_stream() -> Vec<u8> {
    let mut out = Vec::with_capacity(CID_COUNT * 2);
    for gid in &parsed().gids {
        out.extend_from_slice(&gid.to_be_bytes());
    }
    out
}

/// A complete `/W [1 [w1 w2 …]]` entry, widths in 1/1000 em.
pub fn widths_array() -> String {
    let mut s = String::from("/W [1 [");
    for (i, w) in parsed().widths.iter().enumerate().skip(1) {
        if i > 1 {
            s.push(' ');
        }
        let _ = write!(s, "{w}");
    }
    s.push_str("]]");
    s
}

/// The `FontDescriptor` entries that come from the face's metrics.
pub fn descriptor_entries() -> &'static str {
    &parsed().descriptor
}

/// The six PDF objects of the embedded Type0 font, starting at object `id`. Keeping the font's
/// serialization here leaves `PdfDoc::finish` concerned only with numbering and the page tree.
///
/// 1. `id`     — Type0 font (`Identity-H`, descendant, `ToUnicode`)
/// 2. `id + 1` — `CIDFontType2` descendant (`/W`, `/CIDToGIDMap`)
/// 3. `id + 2` — `FontDescriptor` (`/FontFile2`)
/// 4. `id + 3` — the uncompressed TrueType bytes
/// 5. `id + 4` — the `CIDToGIDMap` stream
/// 6. `id + 5` — the `ToUnicode` CMap stream
///
/// Returns nothing when the build has no face, which `PdfDoc::finish` never calls: the font slot
/// stays unused unless [`available`] is true.
pub fn font_objects(id: u32) -> Vec<(u32, Vec<u8>)> {
    let Some(font) = font_bytes() else { return Vec::new() };
    let (cid_id, desc_id, file_id, gidmap_id, unicode_id) = (id + 1, id + 2, id + 3, id + 4, id + 5);
    let name = base_name();
    let mut objects = Vec::with_capacity(6);
    objects.push((
        id,
        format!(
            "<< /Type /Font /Subtype /Type0 /BaseFont /{name} /Encoding /Identity-H /DescendantFonts [{cid_id} 0 R] /ToUnicode {unicode_id} 0 R >>"
        )
        .into_bytes(),
    ));
    objects.push((
        cid_id,
        format!(
            "<< /Type /Font /Subtype /CIDFontType2 /BaseFont /{name} /CIDSystemInfo << /Registry (Adobe) /Ordering (Identity) /Supplement 0 >> /FontDescriptor {desc_id} 0 R /DW 1000 {} /CIDToGIDMap {gidmap_id} 0 R >>",
            widths_array()
        )
        .into_bytes(),
    ));
    objects.push((
        desc_id,
        format!("<< /Type /FontDescriptor /FontName /{name} /Flags 4 {} /FontFile2 {file_id} 0 R >>", descriptor_entries()).into_bytes(),
    ));
    objects.push((file_id, stream(&format!("<< /Length {} /Length1 {} >>", font.len(), font.len()), font)));
    let gidmap = cid_to_gid_stream();
    objects.push((gidmap_id, stream(&format!("<< /Length {} >>", gidmap.len()), &gidmap)));
    let cmap = to_unicode_stream();
    objects.push((unicode_id, stream(&format!("<< /Length {} >>", cmap.len()), &cmap)));
    objects
}

/// One uncompressed PDF stream. `/Length` covers only the data; the newline before `endstream` is
/// the separator the PDF spec requires, matching the streams `lib.rs` writes.
fn stream(dict: &str, data: &[u8]) -> Vec<u8> {
    let mut o = format!("{dict}\nstream\n").into_bytes();
    o.extend_from_slice(data);
    o.extend_from_slice(b"\nendstream");
    o
}

/// A ToUnicode CMap: every CID back to its Unicode scalar, in `bfchar` blocks of at most 100.
pub fn to_unicode_stream() -> Vec<u8> {
    let mut s = String::from(
        "/CIDInit /ProcSet findresource begin\n\
         12 dict begin\n\
         begincmap\n\
         /CIDSystemInfo << /Registry (Adobe) /Ordering (UCS) /Supplement 0 >> def\n\
         /CMapName /Adobe-Identity-UCS def\n\
         /CMapType 2 def\n\
         1 begincodespacerange\n\
         <0000> <FFFF>\n\
         endcodespacerange\n",
    );
    let entries: Vec<(u16, char)> = (1..CID_COUNT).filter_map(|id| character(id as u16).map(|c| (id as u16, c))).collect();
    for chunk in entries.chunks(100) {
        let _ = writeln!(s, "{} beginbfchar", chunk.len());
        for (id, c) in chunk {
            let _ = writeln!(s, "<{id:04X}> <{:04X}>", *c as u32);
        }
        s.push_str("endbfchar\n");
    }
    s.push_str("endcmap\nCMapName currentdict /CMap defineresource pop\nend\nend\n");
    s.into_bytes()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn cids_cover_the_thai_block_only() {
        assert_eq!(cid('ก'), Some(0x0E01 - 0x0E00 + 1));
        assert_eq!(cid('฿'), Some(0x0E3F - 0x0E00 + 1));
        assert_eq!(cid('A'), None);
        assert_eq!(cid('あ'), None);
        assert_eq!(CID_COUNT, 129);
    }

    #[test]
    fn unicode_cmap_covers_every_cid() {
        let bytes = to_unicode_stream();
        let text = String::from_utf8_lossy(&bytes);
        assert!(text.contains("<0001> <0E00>"));
        assert!(text.contains("<0080> <0E7F>"));
        assert!(text.contains("/CMapName /Adobe-Identity-UCS"));
        assert_eq!(cid_to_gid_stream().len(), CID_COUNT * 2);
        assert!(widths_array().starts_with("/W [1 ["));
        assert!(widths_array().ends_with("]]"));
        assert!(descriptor_entries().contains("/Ascent "));
    }

    /// Extended acceptance: only runs when `CRAFT_FONTS_DIR` supplied the Thai face.
    #[test]
    fn embedded_face_has_glyphs_and_positive_widths() {
        if !available() {
            eprintln!("diagnostic: no craft-fonts Thai face embedded; glyph coverage check not run");
            return;
        }
        let p = parsed();
        assert_eq!(p.gids.len(), CID_COUNT);
        for c in ['ก', 'ข', 'ะ', '็', '่', '๐', '๙', '฿'] {
            let id = usize::from(cid(c).unwrap_or(0));
            assert!(p.gids.get(id).copied().unwrap_or(0) > 0, "{c:?} has no glyph");
        }
        assert!(char_width('ก') > 0, "a consonant has an advance width");
        assert_eq!(char_width('ก'), p.widths[usize::from(cid('ก').unwrap_or(0))]);
        assert!(!base_name().is_empty());
    }
}
